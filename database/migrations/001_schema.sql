GRANT SELECT ON catalog.public_products TO order_service;
GRANT USAGE ON SCHEMA auth, private TO order_service;
GRANT SELECT (id, username, password_hash, role) ON auth.users TO order_service;
GRANT SELECT (id, user_id) ON private.customers TO order_service;
GRANT SELECT ON private.orders TO order_service;
GRANT SELECT, INSERT, DELETE ON auth.sessions TO order_service;

-- Deliberately wider read permission, still NOLOGIN until a bounded lab test enables it.
GRANT USAGE ON SCHEMA private TO catalog_reader_wide;
GRANT SELECT ON private.customers, private.orders, private.payment_meta TO catalog_reader_wide;

ALTER ROLE catalog_reader SET search_path = pg_catalog;
ALTER ROLE catalog_reader_wide SET search_path = pg_catalog;
ALTER ROLE order_service SET search_path = pg_catalog;
ALTER ROLE catalog_reader SET statement_timeout = '3s';
ALTER ROLE catalog_reader_wide SET statement_timeout = '3s';
ALTER ROLE order_service SET statement_timeout = '3s';
COMMIT;
