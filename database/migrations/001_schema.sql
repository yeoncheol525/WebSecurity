BEGIN;
CREATE ROLE minishop_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE catalog_reader LOGIN PASSWORD :'reader_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE catalog_reader_wide NOLOGIN PASSWORD :'wide_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE order_service LOGIN PASSWORD :'order_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

REVOKE ALL ON DATABASE :"db_name" FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC;
GRANT CONNECT ON DATABASE :"db_name" TO catalog_reader, catalog_reader_wide, order_service;
REVOKE ALL ON SCHEMA public FROM PUBLIC;

CREATE SCHEMA catalog AUTHORIZATION minishop_owner;
CREATE SCHEMA private AUTHORIZATION minishop_owner;
CREATE SCHEMA auth AUTHORIZATION minishop_owner;
REVOKE ALL ON SCHEMA catalog, private, auth FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE minishop_owner REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE minishop_owner REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE minishop_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

SET ROLE minishop_owner;
CREATE TABLE catalog.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    description text NOT NULL,
    price numeric(12,2) NOT NULL CHECK (price >= 0),
    is_public boolean NOT NULL DEFAULT true
);
-- The requested products table supports SELECT, but restricted roles see public rows only.
ALTER TABLE catalog.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY public_product_read ON catalog.products FOR SELECT
    TO catalog_reader, catalog_reader_wide USING (is_public);
CREATE VIEW catalog.public_products WITH (security_barrier=true) AS
    SELECT id AS item_key, name AS label, description, price AS amount
    FROM catalog.products WHERE is_public;

CREATE TABLE auth.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL DEFAULT 'customer' CHECK (role = 'customer')
);
CREATE TABLE private.customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE REFERENCES auth.users(id),
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    phone text NOT NULL,
    address text NOT NULL
);
CREATE TABLE private.orders (
    id integer PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES private.customers(id),
    product_id integer NOT NULL REFERENCES catalog.products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    order_date timestamptz NOT NULL
);
CREATE INDEX orders_customer_idx ON private.orders(customer_id);
CREATE TABLE private.payment_meta (
    id integer PRIMARY KEY,
    order_id integer NOT NULL UNIQUE REFERENCES private.orders(id),
    method text NOT NULL CHECK (method IN ('TEST_CARD', 'TEST_WALLET')),
    reference text NOT NULL CHECK (reference LIKE 'TEST-%')
);
-- Opaque browser tokens are hashed at rest; logout revokes sessions across workers.
CREATE TABLE auth.sessions (
    token_hash char(64) PRIMARY KEY,
    csrf_hash char(64) NOT NULL,
    user_id integer NOT NULL REFERENCES auth.users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_expiry_idx ON auth.sessions(expires_at);

